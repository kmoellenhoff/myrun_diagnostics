def alias(s):
    s = s.replace("−", "-")
    for suffix in [" (A)", " (K)"]:
        if s.endswith(suffix): s = s[:-len(suffix)]
    for n in [1, 4, 7, 8, 9]: s = s.replace(f"P2.0{n}", f"P2.{n}")
    return {
        "R221-a (Code 2211)": "Q2-R2211.a", "R221-b (Code 2211)": "Q2-R2211.b",
        "R221-a": "Q2-R2211.a", "R221-b": "Q2-R2211.b",
        "Gate-Seite (G oder RG-G; Rohangabe R)": "Q2-G",
    }.get(s, s)


parent = {}
def find(s):
    s = alias(s)
    parent.setdefault(s, s)
    if parent[s] != s: parent[s] = find(parent[s])
    return parent[s]
def union(a, b):
    a, b = find(a), find(b)
    if a != b: parent[b] = a


