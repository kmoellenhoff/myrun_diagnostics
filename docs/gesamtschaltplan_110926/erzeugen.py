def read_csv(path):
    # Some old source rows have extra unquoted semicolons in their comments.
    # Preserve those cells, rather than silently discarding them.
    rows = list(csv.reader(path.open(encoding="utf-8-sig"), delimiter=";"))
    head = rows[0]
    return [dict(zip(head, r[:len(head)])) | ({"Zusatzspalten_original": r[len(head):]} if len(r) > len(head) else {}) for r in rows[1:] if any(r)]


def write_csv(path, rows, columns):
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=columns, delimiter=";", lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: ", ".join(r[k]) if isinstance(r.get(k), list) else r.get(k, "") for k in columns})


