def symbol_sexpr(p):
    ref=p["Reference"]; x,y=p["Position_mm"]; sym=p["Symbol"]
    at = p["Properties"] or ((x-24,y-12),(x-24,y+5))
    # Reference must remain a valid unique CAD ref; repository alias is a separate
    # visible property, not inserted into the actual Reference field.
    props = f'(property "Reference" {q(ref)} (at {xy(at[0])} 0) {effects(1.7,"left")})'
    props += f'(property "Value" {q(p["Wert"])} (at {xy(at[1])} 0) {effects(1.8,"left",hide=ref=="J201")})'
    props += f'(property "Repository_ID" {q(p["Repository_ID"])} (at {at[0][0]} {at[0][1]-4} 0) {effects(1.7,"left")})'
    for key,val in [("Feld_Claude",p["Feld_Claude"]),("Messwerte",p["Messwerte"]),("Terminal_Aliase",json.dumps(p["Terminals"],ensure_ascii=False))]:
        props += f'(property {q(key)} {q(val)} (at {x} {y} 0) {effects(1.5,hide=True)})'
    pins = "".join(f'(pin {q(k)} (uuid "{uid(ref+".pin."+k)}"))' for k in p["Terminals"])
    return f'''(symbol (lib_id "Diag:{sym}") (at {x} {y} 0) (unit 1) (exclude_from_sim yes) (in_bom no) (on_board no) (dnp {"yes" if p.get("DNP") else "no"}) (uuid "{uid(ref)}")
    {props} {pins} (instances (project "{STEM}" (path "/{ROOT_UUID}" (reference {q(ref)}) (unit 1)))))'''


def save_schematic(width=841, height=1250, title="GIRT S6T30 - rekonstruierte Originalschaltung"):
    txt = f'(kicad_sch (version 20250114) (generator "eeschema") (uuid "{ROOT_UUID}") (paper "User" {width} {height})\n'
    txt += f'(title_block (title {q(title)}) (date "{DOC_DATE}") (rev "main / Evidenzmodell") (company "myrun_diagnostics") (comment 1 "M gemessen / F Foto / I abgeleitet; keine vollstaendige Platinenrekonstruktion"))\n'
    txt += '(lib_symbols\n' + "\n".join(v["text"] for v in libraries.values()) + ')\n'
    txt += "\n".join(drawing) + "\n"
    # KiCad expects T junctions to be explicit wire endpoints. Merely placing
    # a junction dot over the middle of an unsplit segment is insufficient.
    vertices=set(p for segment in wires for p in segment) | junctions | set(p for _,p,_ in labels)
    vertices |= {v for part in parts for v in part["Pins_xy"].values()}
    segments=set()
    for a,b in wires:
        on=[p for p in vertices if min(a[0],b[0])<=p[0]<=max(a[0],b[0]) and min(a[1],b[1])<=p[1]<=max(a[1],b[1]) and (p[0]==a[0]==b[0] or p[1]==a[1]==b[1])]
        on.sort(key=lambda p:(p[0],p[1]))
        segments.update(tuple(sorted((c,d))) for c,d in zip(on,on[1:]) if c!=d)
    for i,(a,b) in enumerate(sorted(segments)):
        txt += f'(wire (pts (xy {xy(a)}) (xy {xy(b)})) (stroke (width .35) (type default)) (uuid "{uid("wire"+str(i))}"))\n'
    for i,(name,p,size) in enumerate(labels):
        txt += f'(label {q(name)} (at {xy(p)} 0) {effects(size,"left bottom")} (uuid "{uid("label"+str(i))}"))\n'
    for p in sorted(junctions):
        txt += f'(junction (at {xy(p)}) (diameter 1) (color 0 0 0 0) (uuid "{uid("junction"+str(p))}"))\n'
    txt += "\n".join(symbol_sexpr(p) for p in parts)
    txt += '\n(sheet_instances (path "/" (page "1"))) (embedded_fonts no))\n'
    (HERE / (STEM+".kicad_sch")).write_text(txt)


